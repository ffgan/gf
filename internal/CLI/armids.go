package cli

// ARM implementer and part names follow the util-linux lscpu tables
// that fastfetch ships. A part that is not in the table is reported
// as the vendor plus the hexadecimal id, never a guessed name.

func armVendor(impl uint32) string {
	if s, ok := armVendors[impl]; ok && s != "Unknown" {
		return s
	}
	return ""
}

func armPartName(impl, part uint32) (string, bool) {
	m := armParts[impl]
	if m == nil {
		return "", false
	}
	s, ok := m[part]
	return s, ok
}

